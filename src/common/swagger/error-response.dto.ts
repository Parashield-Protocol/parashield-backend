import { ApiProperty } from '@nestjs/swagger';
import { ErrorCode } from '../errors/error-codes';

/**
 * RFC 7807 Problem Details response envelope returned by GlobalExceptionFilter
 * for all error responses (#677). Served with Content-Type `application/problem+json`.
 *
 * Conforms to RFC 7807. Legacy envelope fields (success, statusCode, error,
 * message, errorCode, path, timestamp) remain present alongside the standard
 * problem members for backward compatibility, but are deprecated.
 */
export class ErrorResponseDto {
  // ── RFC 7807 Standard Members ──────────────────────────────────────────────
  @ApiProperty({
    description: 'A URI reference that identifies the problem type per RFC 7807.',
    example: 'https://parashield.io/errors/not-found',
  })
  type: string;

  @ApiProperty({
    description: 'A short, human-readable summary of the problem type per RFC 7807.',
    example: 'Not Found',
  })
  title: string;

  @ApiProperty({
    description: 'The HTTP status code generated by the origin server for this occurrence of the problem.',
    example: 404,
  })
  status: number;

  @ApiProperty({
    description: 'A human-readable explanation specific to this occurrence of the problem.',
    example: 'Policy not found',
  })
  detail: string;

  @ApiProperty({
    description: 'A URI reference that identifies the specific occurrence of the problem (request path).',
    example: '/api/v1/policies/abc123',
    required: false,
  })
  instance?: string;

  @ApiProperty({
    description: 'Detailed list of validation or field errors (present on validation failures).',
    required: false,
  })
  errors?: unknown;

  @ApiProperty({
    description: 'Unique correlation ID associated with the request (from X-Correlation-ID / X-Request-ID header).',
    example: 'req_1234567890',
    required: false,
  })
  correlationId?: string;

  // ── Backward Compatibility Fields (Deprecated) ─────────────────────────────
  @ApiProperty({
    description: 'Deprecated: Use RFC 7807 members. Always false for error responses.',
    example: false,
    deprecated: true,
  })
  success: boolean;

  @ApiProperty({
    description:
      'Deprecated: Use `type` per RFC 7807. Stable machine-readable error code.',
    enum: ErrorCode,
    example: ErrorCode.NOT_FOUND,
    deprecated: true,
  })
  errorCode: ErrorCode;

  @ApiProperty({
    description:
      'Deprecated: Use `detail` per RFC 7807. Human-readable error message.',
    oneOf: [
      { type: 'string', example: 'Policy not found' },
      {
        type: 'object',
        properties: {
          message: {
            oneOf: [
              { type: 'string' },
              { type: 'array', items: { type: 'string' } },
            ],
          },
          error: { type: 'string', example: 'Bad Request' },
          statusCode: { type: 'integer', example: 400 },
        },
      },
    ],
    deprecated: true,
  })
  error: string | object;

  @ApiProperty({
    description: 'Deprecated: Use `detail` per RFC 7807. String message.',
    example: 'Policy not found',
    deprecated: true,
  })
  message: string;

  @ApiProperty({
    description: 'Deprecated: Use `status` per RFC 7807. HTTP status code.',
    example: 404,
    deprecated: true,
  })
  statusCode: number;

  @ApiProperty({
    description: 'Deprecated: Use `instance` per RFC 7807. The request path that produced the error.',
    example: '/api/v1/policies/abc123',
    deprecated: true,
  })
  path: string;

  @ApiProperty({
    description: 'Deprecated: ISO-8601 UTC timestamp at which the error occurred.',
    example: '2024-01-15T10:30:00.000Z',
    deprecated: true,
  })
  timestamp: string;

  @ApiProperty({
    description:
      'Seconds to wait before retrying. Present **only** on 429 responses once rate limit is exceeded.',
    example: 42,
    required: false,
  })
  retryAfter?: number;
}

// ---------------------------------------------------------------------------
// Per-errorCode example payloads used by Swagger UI decorators.
// ---------------------------------------------------------------------------

function errorExample(
  errorCode: ErrorCode,
  statusCode: number,
  title: string,
  detail: string,
  path = '/api/v1/resource',
  retryAfter?: number,
  errors?: unknown,
) {
  const slug = errorCode.toLowerCase().replace(/_/g, '-');
  return {
    type: `https://parashield.io/errors/${slug}`,
    title,
    status: statusCode,
    detail,
    instance: path,
    ...(errors !== undefined ? { errors } : {}),
    success: false,
    statusCode,
    message: detail,
    error: detail,
    errorCode,
    path,
    timestamp: '2024-01-15T10:30:00.000Z',
    ...(retryAfter !== undefined ? { retryAfter } : {}),
  };
}

